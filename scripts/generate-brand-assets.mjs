import {
  readFileSync,
  writeFileSync,
  mkdirSync,
  mkdtempSync,
  copyFileSync,
  rmSync
} from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { execFileSync } from 'node:child_process';

const root = fileURLToPath(new URL('../', import.meta.url));
const mark = JSON.parse(
  readFileSync(join(root, 'apps/web/src/assets/prism-fold.json'), 'utf8')
);
const require = createRequire(
  new URL('../packages/geometry/package.json', import.meta.url)
);
const { parse } = require('opentype.js');
const fontBytes = readFileSync(
  join(
    root,
    'apps/web/node_modules/@fontsource/geist-sans/files/geist-sans-latin-500-normal.woff'
  )
);
const font = parse(
  fontBytes.buffer.slice(
    fontBytes.byteOffset,
    fontBytes.byteOffset + fontBytes.byteLength
  )
);
const wordmark = font
  .getPath('OpenZCAD', 126, 67, 48, { kerning: true })
  .toPathData(3);
const wordmarkWidth = font.getAdvanceWidth('OpenZCAD', 48, { kerning: true });
const colorPaths =
  `<path d="${mark.silhouette}" fill="${mark.colors.front}"/>\n` +
  mark.faces
    .map((face) => `<path d="${face.d}" fill="${mark.colors[face.tone]}"/>`)
    .join('\n');
const monoPath = `<path d="${mark.silhouette}" fill="currentColor"/>`;
const header =
  '<!-- Generated by pnpm brand:generate. Source: src/assets/prism-fold.json. -->\n';
function svg(viewBox, body, label) {
  return `${header}<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" role="img" aria-label="${label}">\n${body}\n</svg>\n`;
}
const assets = new Map([
  ['apps/web/public/brand/mark.svg', svg(mark.viewBox, colorPaths, 'OpenZCAD')],
  [
    'apps/web/public/brand/mark-monochrome.svg',
    svg(mark.viewBox, monoPath, 'OpenZCAD')
  ],
  [
    'apps/web/public/brand/logo.svg',
    svg(
      `0 0 ${Math.ceil(126 + wordmarkWidth + 4)} 100`,
      `${colorPaths}\n<path d="${wordmark}" fill="#111827"/>`,
      'OpenZCAD'
    )
  ],
  [
    'apps/web/public/brand/logo-light.svg',
    svg(
      `0 0 ${Math.ceil(126 + wordmarkWidth + 4)} 100`,
      `${colorPaths}\n<path d="${wordmark}" fill="#f3f4f6"/>`,
      'OpenZCAD'
    )
  ],
  [
    'apps/web/public/brand/app-icon.svg',
    svg(
      '0 0 1024 1024',
      `<rect x="48" y="48" width="928" height="928" rx="208" fill="${mark.colors.tile}"/>\n<g transform="translate(152 152) scale(7.2)">\n${colorPaths}\n</g>`,
      'OpenZCAD app icon'
    )
  ],
  [
    'apps/web/public/favicon.svg',
    svg(mark.compactViewBox, colorPaths, 'OpenZCAD')
  ]
]);

const check = process.argv.includes('--check');
let stale = false;
for (const [relative, contents] of assets) {
  const path = join(root, relative);
  if (check) {
    let actual;
    try {
      actual = readFileSync(path, 'utf8');
    } catch {
      /* Report missing alongside stale assets. */
    }
    if (actual !== contents) {
      console.error(`Stale brand asset: ${relative}`);
      stale = true;
    }
  } else {
    mkdirSync(join(path, '..'), { recursive: true });
    writeFileSync(path, contents);
  }
}
if (stale) process.exitCode = 1;
if (!check) {
  // Use the already-pinned Tauri renderer for portable PNG/ICNS generation.
  // Its other platform outputs remain temporary; only the shipped assets are copied.
  const temporary = mkdtempSync(join(tmpdir(), 'openzcad-brand-'));
  try {
    const tauri = join(
      root,
      'apps/desktop/node_modules/@tauri-apps/cli/tauri.js'
    );
    const render = (source, output, sizes = []) =>
      execFileSync(
        process.execPath,
        [
          tauri,
          'icon',
          join(root, source),
          '--output',
          output,
          ...sizes.flatMap((size) => ['--png', String(size)])
        ],
        { cwd: root, stdio: 'pipe' }
      );
    render('apps/web/public/brand/app-icon.svg', join(temporary, 'desktop'));
    for (const name of ['icon.png', 'icon.icns']) {
      copyFileSync(
        join(temporary, 'desktop', name),
        join(root, 'apps/desktop/src-tauri/icons', name)
      );
    }
    render('apps/web/public/favicon.svg', join(temporary, 'favicon'), [16, 32]);
    for (const size of [16, 32]) {
      copyFileSync(
        join(temporary, 'favicon', `${size}x${size}.png`),
        join(root, `apps/web/public/favicon-${size}.png`)
      );
    }
    render(
      'apps/web/public/brand/app-icon.svg',
      join(temporary, 'touch'),
      [180]
    );
    copyFileSync(
      join(temporary, 'touch', '180x180.png'),
      join(root, 'apps/web/public/apple-touch-icon.png')
    );
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
  console.log('Generated Prism Fold SVG, PNG, and desktop icon assets.');
}

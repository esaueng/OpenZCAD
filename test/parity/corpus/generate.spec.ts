function primitiveDocument(
  name: string,
  primitiveKind: 'box' | 'cylinder' | 'cone' | 'sphere',
  dimensions: Record<string, number>
): ProjectDocument {
  return addPrimitiveFeature(
    createProjectDocument(name, GENERATOR_USER, 'mm'),
    {
      name,
      primitiveKind,
      dimensions
    }
  );
}

function boredPlateDocument(): { document: ProjectDocument; bodyId: BodyId } {
  const manager = new CommandManager(
    createProjectDocument('Bored plate', GENERATOR_USER, 'mm')
  );
  const plate = createBodyFeatureIds();
  const bore = createBodyFeatureIds();
  const cut = createBodyFeatureIds();
  manager.runTransaction('Bore the plate', [
    commandFactories.addPrimitive({
      name: 'Plate',
      primitiveKind: 'box',
      dimensions: { width: 40, height: 24, depth: 10 },
      ids: plate
    }),
    commandFactories.addPrimitive({
      name: 'Bore',
      primitiveKind: 'cylinder',
      dimensions: { radius: 5, height: 30 },
      ids: bore
    }),
    commandFactories.transformBody({
      name: 'Seat the bore',
      targetBodyId: bore.bodyId,
      translation: { x: 20, y: 12, z: -10 }
    }),
    commandFactories.booleanBodies({
      name: 'Bored plate',
      operation: 'subtract',
      targetBodyIds: [plate.bodyId, bore.bodyId],
      ids: cut
    })
  ]);
  return { document: manager.document, bodyId: cut.bodyId };
}

/**
 * The four vertical corner edges of the modeling base plate, picked by
 * position exactly the way an interactive edge pick resolves them.
 */
export function verticalCornerEdgeHashes(
  edges: ReadonlyArray<{ hash: number; points: number[] }>,
  height: number
): number[] {
  return edges
    .filter((edge) => {
      const min = [Infinity, Infinity, Infinity];
      const max = [-Infinity, -Infinity, -Infinity];
      for (let index = 0; index < edge.points.length; index += 3) {
        for (let axis = 0; axis < 3; axis += 1) {
          const value = edge.points[index + axis]!;
          min[axis] = Math.min(min[axis]!, value);
          max[axis] = Math.max(max[axis]!, value);
        }
      }
      return (
        max[2]! - min[2]! >= height - 1 &&
        max[0]! - min[0]! < 1 &&
        max[1]! - min[1]! < 1
      );
    })
    .map((edge) => edge.hash);
}

/**
 * A filleted plate built and exported through the given adapter. Remus
 * writes the four fillet bands as B-splines and OCCT writes them as cylinders
 * — the two encodings that make up the (e) category.
 */
async function filletedPlateStep(
  adapter: RemusKernelAdapter | OcctStepKernelAdapter,
  plateStep: string
): Promise<string> {
  const manager = new CommandManager(
    createProjectDocument('Filleted plate', GENERATOR_USER, 'mm')
  );
  const imported = createBodyFeatureIds();
  manager.execute(
    commandFactories.importStep({
      name: 'Plate',
      artifactId: 'artifact_corpus_plate',
      sourceName: 'modeling-base-plate.step',
      stepText: plateStep,
      ids: imported
    })
  );
  const derived = await adapter.syncDocument(manager.document);
  const edges = derived.bodyRepresentations[imported.bodyId]?.topology?.edges;
  if (!edges) {
    throw new Error('base plate imported without topology');
  }
  const corners = verticalCornerEdgeHashes(edges, MODELING_BASE.height);
  if (corners.length !== 4) {
    throw new Error(
      `expected 4 vertical corner edges on the base plate, found ${corners.length}`
    );
  }
  const fillet = createBodyFeatureIds();
  manager.runTransaction('Break the corners', [
    commandFactories.filletEdges({
      name: 'Corner break',
      targetBodyId: imported.bodyId,
      edgeHashes: corners,
      size: 3,
      ids: fillet
    })
  ]);
  await adapter.syncDocument(manager.document);
  return adapter.exportStep(manager.document, [fillet.bodyId]);
}


/**
 * Corpus file generator.
 *
 * Regenerate every corpus-owned `.step` file with:
 *
 *   OPENZCAD_WRITE_PARITY_CORPUS=1 pnpm test:parity-corpus
 *
 * Without that env var this file VERIFIES that the committed hand-authored and
 * derived files are still exactly what the generator produces, so a corpus
 * file cannot be edited in place without the suite noticing. Adapter-exported
 * files are not byte-compared — a kernel version bump legitimately changes
 * their bytes, which is why they are committed rather than produced at
 * measurement time.
 *
 * Corpus files are committed on purpose. If they were generated during the
 * measurement run, a kernel regression would silently rewrite the very inputs
 * meant to detect it.
 */


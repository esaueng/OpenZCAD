const WRITE = process.env.OPENZCAD_WRITE_PARITY_CORPUS === '1';
const GENERATOR_USER = toUserId('user_parity_corpus');

/** Files produced by exporting through a kernel; bytes move with the kernel. */
const EXPORTED_IDS = [
  'a-export-box',
  'a-export-cylinder',
  'a-export-cone',
  'a-export-sphere',
  'a-export-bored-plate',
  'e-nurbs-fillet-plate',
  'e-analytic-fillet-plate',
  'f-hostile-occt-authored-box'
] as const;

function corpusPath(id: string): string {
  return join(REPO_ROOT, 'test', 'parity', 'corpus', `${id}.step`);
}

function readCorpus(id: string): string {
  return readFileSync(corpusPath(id), 'utf8');
}

function purposeOf(id: string): string {
  const entry = CORPUS.find((candidate) => candidate.id === id);
  if (!entry) {
    throw new Error(
      `generator emits '${id}' but the manifest does not list it`
    );
  }
  return entry.purpose;
}

/**
 * Corpus files must say what they are. Adapter exports are opaque, so the
 * purpose goes in as a STEP comment at the top of the DATA section — the one
 * place both parsers demonstrably tolerate free text (`scanStepEntities` in
 * `step-import.ts` skips STEP comment blocks, and so do both kernels).
 */
function annotate(id: string, step: string, generated: boolean): string {
  const wrapped = purposeOf(id)
    .replace(/(.{1,70})(\s|$)/g, '   $1\n')
    .trimEnd();
  const lines = [`/* corpus: ${id}`, wrapped];
  if (generated) {
    lines.push(
      '',
      '   Generated by exporting through a kernel adapter. Do not hand-edit;',
      '   rerecord with OPENZCAD_WRITE_PARITY_CORPUS=1 (see corpus/README.md).'
    );
  }
  lines.push('*/');
  const comment = lines.join('\n');
  const dataIndex = step.indexOf('DATA;');
  if (dataIndex < 0) {
    throw new Error(`${id}: exported STEP has no DATA section to annotate`);
  }
  const insertAt = dataIndex + 'DATA;'.length;
  return `${step.slice(0, insertAt)}\n${comment}${step.slice(insertAt)}`;
}


describe('parity corpus files', () => {
  let remus: RemusKernelAdapter;
  let occt: OcctStepKernelAdapter;

  beforeAll(async () => {
    if (!WRITE) {
      return;
    }
    remus = new RemusKernelAdapter();
    occt = await OcctStepKernelAdapter.create();
  }, 120_000);

  afterAll(() => {
    remus?.dispose();
    occt?.dispose();
  });

  it.runIf(WRITE)(
    'regenerates the adapter-exported files',
    async () => {
      const plateStep = modelingBasePlateText();

      const produce: Record<
        (typeof EXPORTED_IDS)[number],
        () => Promise<string>
      > = {
        'a-export-box': async () => {
          const document = primitiveDocument('Box', 'box', {
            width: 10,
            height: 20,
            depth: 30
          });
          return remus.exportStep(document, [document.bodyOrder[0]!]);
        },
        'a-export-cylinder': async () => {
          const document = primitiveDocument('Cylinder', 'cylinder', {
            radius: 8,
            height: 20
          });
          return remus.exportStep(document, [document.bodyOrder[0]!]);
        },
        'a-export-cone': async () => {
          const document = primitiveDocument('Cone', 'cone', {
            bottomRadius: 10,
            topRadius: 0,
            height: 10
          });
          return remus.exportStep(document, [document.bodyOrder[0]!]);
        },
        'a-export-sphere': async () => {
          const document = primitiveDocument('Sphere', 'sphere', {
            radius: 6
          });
          return remus.exportStep(document, [document.bodyOrder[0]!]);
        },
        'a-export-bored-plate': async () => {
          const { document, bodyId } = boredPlateDocument();
          await remus.syncDocument(document);
          return remus.exportStep(document, [bodyId]);
        },
        'e-nurbs-fillet-plate': () => filletedPlateStep(remus, plateStep),
        'e-analytic-fillet-plate': () => filletedPlateStep(occt, plateStep),
        'f-hostile-occt-authored-box': async () => {
          const document = primitiveDocument('Box', 'box', {
            width: 10,
            height: 20,
            depth: 30
          });
          return occt.exportStep(document, [document.bodyOrder[0]!]);
        }
      };

      for (const id of EXPORTED_IDS) {
        writeFileSync(corpusPath(id), annotate(id, await produce[id](), true));
      }
    },
    600_000
  );

  it('reproduces every hand-authored file byte for byte', () => {
    for (const { id, text } of authoredFiles()) {
      if (WRITE) {
        writeFileSync(corpusPath(id), text);
        continue;
      }
      expect(
        readCorpus(id),
        `${id}.step differs from what step-authoring.ts produces. Either the ` +
          'file was hand-edited (regenerate it instead) or the authoring ' +
          'helper changed (rerecord with OPENZCAD_WRITE_PARITY_CORPUS=1).'
      ).toBe(text);
    }
  });

  it('reproduces every derived file byte for byte', () => {
    for (const { id, text } of derivedFiles()) {
      if (WRITE) {
        writeFileSync(corpusPath(id), text);
        continue;
      }
      expect(
        readCorpus(id),
        `${id}.step is no longer the documented rewrite of its source file.`
      ).toBe(text);
    }
  });

  it('every manifest entry has a file on disk', () => {
    for (const entry of CORPUS) {
      expect(
        () => readFileSync(join(REPO_ROOT, entry.path), 'utf8'),
        `${entry.id}: ${entry.path} is missing — regenerate with ` +
          'OPENZCAD_WRITE_PARITY_CORPUS=1'
      ).not.toThrow();
    }
    expect(() =>
      readFileSync(join(REPO_ROOT, MODELING_BASE.path), 'utf8')
    ).not.toThrow();
  });

  it('every corpus-owned file names itself in a STEP comment', () => {
    const owned = CORPUS.filter((entry) =>
      entry.path.startsWith('test/parity/corpus/')
    );
    expect(owned.length).toBeGreaterThan(0);
    for (const entry of owned) {
      const text = readCorpus(entry.id);
      expect(
        text.startsWith('ISO-10303-21;'),
        `${entry.id} lost its magic`
      ).toBe(true);
      expect(text, `${entry.id} carries no corpus comment`).toContain(
        `/* corpus: ${entry.id}`
      );
    }
  });

  it('keeps the degree variants provably derived from the same cone', () => {
    const cone = readCorpus('a-export-cone');
    const degree = readCorpus('b-unit-degree-cone');
    const unassigned = readCorpus('b-unit-degree-cone-unassigned');

    const halfAngle = (step: string) =>
      Number(/CONICAL_SURFACE\s*\([^;]*,\s*([\d.E+-]+)\s*\)/i.exec(step)?.[1]);

    expect(halfAngle(cone)).toBeCloseTo(Math.PI / 4, 12);
    expect(halfAngle(degree)).toBeCloseTo(45, 10);
    expect(halfAngle(unassigned)).toBeCloseTo(45, 10);

    // Compare the entity text, not the corpus comment — the comment names the
    // very entity the -unassigned variant is missing.
    const entities = (step: string) => stripCorpusComment(step);
    expect(entities(degree)).toContain('GLOBAL_UNIT_ASSIGNED_CONTEXT');
    expect(entities(degree)).toContain("CONVERSION_BASED_UNIT('DEGREE'");
    // The whole point of the -unassigned variant: no assigned context, so
    // nothing in the file binds a unit and no reader can prove a scale.
    expect(entities(unassigned)).not.toContain('GLOBAL_UNIT_ASSIGNED_CONTEXT');
    expect(entities(unassigned)).toContain("CONVERSION_BASED_UNIT('DEGREE'");
  });
});

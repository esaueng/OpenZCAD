/**
 * The plate every import-modeling scenario is layered on. Kept as a function
 * so the generator's export step can use the same bytes it commits, rather
 * than depending on test execution order.
 */
export function modelingBasePlateText(): string {
  return writeBoxStepFile({
    id: 'modeling-base-plate',
    purpose:
      'The shared base body for the import-modeling scenarios: a ' +
      `${MODELING_BASE.width}x${MODELING_BASE.depth}x${MODELING_BASE.height} mm ` +
      'plate, all planar, so fillet-on-import / boolean-with-import / ' +
      'shell-on-import measure the operation rather than the import.',
    solids: [
      {
        name: 'Plate',
        outer: {
          min: { x: 0, y: 0, z: 0 },
          max: {
            x: MODELING_BASE.width,
            y: MODELING_BASE.depth,
            z: MODELING_BASE.height
          }
        }
      }
    ]
  });
}

/**
 * Files derived by rewriting a committed corpus file. Deterministic given the
 * input, so these are byte-verified too — which is what keeps the degree
 * variants provably the same cone as `a-export-cone`.
 */
function derivedFiles(): Array<{ id: string; text: string }> {
  const degreeCone = annotate(
    'b-unit-degree-cone',
    declareDegreePlaneAngles(stripCorpusComment(readCorpus('a-export-cone'))),
    true
  );
  return [
    { id: 'b-unit-degree-cone', text: degreeCone },
    {
      id: 'b-unit-degree-cone-unassigned',
      text: annotate(
        'b-unit-degree-cone-unassigned',
        stripGlobalUnitContext(stripCorpusComment(degreeCone)),
        true
      )
    }
  ];
}

function stripCorpusComment(step: string): string {
  return step.replace(/\n\/\* corpus:[\s\S]*?\*\//, '');
}

/** Remove one named ADVANCED_FACE from every CLOSED_SHELL that lists it. */
function dropFaceFromShell(step: string, faceName: string): string {
  const face = new RegExp(`#(\\d+)=ADVANCED_FACE\\('${faceName}'`).exec(step);
  if (!face) {
    throw new Error(`no ADVANCED_FACE named '${faceName}' to drop`);
  }
  const id = `#${face[1]}`;
  const dropped = step.replace(
    /CLOSED_SHELL\('([^']*)',\(([^)]*)\)\)/g,
    (_match, label: string, members: string) =>
      `CLOSED_SHELL('${label}',(${members
        .split(',')
        .filter((member) => member !== id)
        .join(',')}))`
  );
  if (dropped === step) {
    throw new Error(`'${faceName}' was not a member of any CLOSED_SHELL`);
  }
  return dropped;
}

/** Point one face's surface at an entity id that is not in the file. */
function danglePlaneReference(step: string, faceName: string): string {
  const pattern = new RegExp(
    `(#\\d+=ADVANCED_FACE\\('${faceName}',\\([^)]*\\),)#\\d+(,\\.[TF]\\.\\);)`
  );
  if (!pattern.test(step)) {
    throw new Error(`no ADVANCED_FACE named '${faceName}' to break`);
  }
  return step.replace(pattern, '$1#999999$2');
}

